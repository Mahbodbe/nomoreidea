def build_404():
    lang = "en"
    s = STR[lang]
    hd = head(lang, f'{s["nf_title"]} | {NAME_EN}', s["nf_text"], f"{SITE}/404.html", [], {"@context": "https://schema.org"},
              robots="noindex, follow", preload=False)
    body = f'<section class="band proj-head"><div class="shell"><h1>{esc(s["nf_title"])}</h1><p class="lede">{esc(s["nf_text"])}</p><div class="proj-actions"><a class="btn-solid" href="/">{esc(s["home"])}</a><a class="cta-type" href="/fa/">فارسی</a></div></div></section>'
    wr("404.html", page_shell(lang, hd, body, "/fa/"))


def build_sitemap():
    def entry(slug_path, lastmod, en_url, fa_url):
        loc = en_url if slug_path == "en" else fa_url
        return (f"  <url>\n    <loc>{loc}</loc>\n    <lastmod>{lastmod}</lastmod>\n"
                f'    <xhtml:link rel="alternate" hreflang="en" href="{en_url}" />\n'
                f'    <xhtml:link rel="alternate" hreflang="fa" href="{fa_url}" />\n'
                f'    <xhtml:link rel="alternate" hreflang="x-default" href="{en_url}" />\n  </url>')
    rows = [entry("en", HOME_LASTMOD, home_url("en"), home_url("fa")),
            entry("fa", HOME_LASTMOD, home_url("en"), home_url("fa"))]
    for slug in CFG["pinned"]:
        if slug in PROJECTS:
            rows.append(entry("en", LASTMOD, proj_url("en", slug), proj_url("fa", slug)))
            rows.append(entry("fa", LASTMOD, proj_url("en", slug), proj_url("fa", slug)))
    wr("sitemap.xml", '<?xml version="1.0" encoding="UTF-8"?>\n'
       '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
       + "\n".join(rows) + "\n</urlset>\n")


def main():
    write_runtime()
    for lang in ("en", "fa"):
        build_home(lang)
        for slug in PROJECTS:
            build_project(slug, lang)
    build_404()
    build_sitemap()
    print("build ok:", HOME_LASTMOD)


if __name__ == "__main__":
    main()
