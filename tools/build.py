def card_html(r, lang):
    dot = LANG_COLORS.get(r.get("language") or "", "")
    topics = "".join(f"<li>{esc(x)}</li>" for x in (r.get("topics") or [])[:4])
    pinned = r["name"] in CFG["pinned"]
    body = r.get("excerpt") or r.get("description") or ""
    flag = '<span class="flag-pin" title="featured">★</span>' if pinned else ""
    style = f' style="--lang-dot:{dot}"' if dot else ""
    lang_html = (f'<span class="pcard__lang"><i aria-hidden="true"></i>{esc(r["language"])}</span>'
                 if r.get("language") else "<span></span>")
    upd = STR[lang]["rel_updated"]
    return (f'<a class="pcard" href="{esc(r["url"])}" target="_blank" rel="noreferrer" '
            f'data-repo="{esc(r["full_name"])}"{style}>'
            f'<div class="pcard__top"><span class="pcard__name">{esc(r["name"])} {flag}</span>'
            f'<span class="pcard__go" aria-hidden="true">↗</span></div>'
            f'<p class="pcard__excerpt">{esc(body) or "&nbsp;"}</p>'
            + (f'<ul class="pcard__topics">{topics}</ul>' if topics else "")
            + f'<div class="pcard__foot">{lang_html}<span title="stars">★ {r.get("stars", 0)}</span>'
              f'<span title="forks">⑂ {r.get("forks", 0)}</span><span class="pcard__spacer"></span>'
              f'<span>{esc(upd)} {esc(rel_time(r.get("pushed_at"), lang))}</span></div></a>')


def grid_html(lang):
    repos = [r for r in SNAP.get("repos", []) if r["name"] not in CFG["hidden"]]
    return "\n".join("        " + card_html(r, lang) for r in repos)


def featured_html(lang):
    out = []
    for slug in CFG["pinned"]:
        pj = PROJECTS.get(slug)
        if not pj:
            continue
        c = pj[lang]
        topics = "".join(f"<li>{esc(x)}</li>" for x in pj["stack"][:4])
        summary = c["summary"].split(". ")[0].rstrip(".") + "."
        out.append(
            f'        <a class="pcard pcard--page" href="{prefix(lang)}/projects/{sl(slug)}/">'
            f'<div class="pcard__top"><span class="pcard__name">{esc(c["title"])}</span>'
            f'<span class="pcard__go" aria-hidden="true">→</span></div>'
            f'<p class="pcard__excerpt">{esc(summary)}</p><ul class="pcard__topics">{topics}</ul>'
            f'<div class="pcard__foot"><span class="pcard__lang"><i aria-hidden="true"></i>{esc(pj["kind"])}</span>'
            f'<span class="pcard__spacer"></span><span>{esc(STR[lang]["read_more"])}</span></div></a>')
    return "\n".join(out)


def fill_i18n(page, lang):
    s = STR[lang]

    def sub_text(m):
        key = m.group("key")
        if key not in s or not isinstance(s[key], str):
            raise KeyError(f"missing i18n key: {key}")
        return f'<{m.group("tag")}{m.group("attrs")}>{s[key]}</{m.group("tag")}>'

    page = re.sub(r'<(?P<tag>[a-zA-Z0-9]+)(?P<attrs>[^<>]*?\sdata-i18n="(?P<key>[^"]+)"[^<>]*)>(?P<inner>.*?)</(?P=tag)>',
                  sub_text, page, flags=re.S)

    def sub_ph(m):
        tag = m.group(0)
        key = re.search(r'data-i18n-ph="([^"]+)"', tag).group(1)
        return re.sub(r'placeholder="[^"]*"', f'placeholder="{esc(s[key])}"', tag)

    page = re.sub(r"<input[^>]*data-i18n-ph=[^>]*>", sub_ph, page)
    return page


