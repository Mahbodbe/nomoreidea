def page_shell(lang, head_html, body, alt_href):
    s = STR[lang]
    other = "fa" if lang == "en" else "en"
    return PAGE_TPL.format(
        lang=lang, dir=s["dir"], head=head_html, bodyclass="fa-mode" if lang == "fa" else "",
        home=f"{prefix(lang)}/" or "/", brand=s["brand"], nav_work=s["nav_work"], nav_about=s["nav_about"],
        nav_contact=s["nav_contact"], alt_href=alt_href, alt_lang=other, switch=esc(s["switch_language"]),
        en_a=" is-active" if lang == "en" else "", fa_a=" is-active" if lang == "fa" else "",
        body=body, footer=s["footer_text"], home_label=s["home"])


