#!/usr/bin/env python3
"""build.py — generate the static pages of nomoreidea.ir.

Single source of truth:
  content/en.json, content/fa.json   UI strings for both languages
  content/projects.json              featured project pages (EN + FA)
  content/site.json                  hidden / pinned repositories
  data/projects.json                 GitHub snapshot (tools/sync_projects.py)
  src/template.html                  page skeleton

Outputs (committed, served by GitHub Pages):
  index.html, fa/index.html          home pages (real HTML in each language)
  projects/<slug>/index.html         featured project pages (+ fa/ copies)
  js/i18n.en.js, js/i18n.fa.js       runtime strings for dynamic UI text
  js/site-config.js, sitemap.xml, 404.html

Run:  python tools/build.py        (needs only the Python standard library)
"""
from __future__ import annotations

import datetime as dt
import hashlib
import html
import json
import os
import re
import subprocess

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SITE = "https://nomoreidea.ir"
NAME_EN = "Mahbod BemaniCham"
NAME_FA = "مهبد بمانی‌چم"
OG_IMAGE = f"{SITE}/images/og-image.jpg"
LOCALES = {"en": "en_US", "fa": "fa_IR"}


def rd(*p):
    with open(os.path.join(ROOT, *p), encoding="utf-8") as f:
        return f.read()


def wr(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def jl(*p):
    return json.loads(rd(*p))


def norm(v):
    if isinstance(v, str):
        return re.sub(r"\s+", " ", v).strip()
    return v


STR = {l: {k: norm(v) for k, v in jl("content", f"{l}.json").items()} for l in ("en", "fa")}
PROJECTS = jl("content", "projects.json")
CFG = jl("content", "site.json")
try:
    SNAP = jl("data", "projects.json")
except OSError:
    SNAP = {"repos": [], "stats": {}}

# ───────────────────────── helpers ─────────────────────────
_h = {}


def asset(path):
    """/css/site.css -> /css/site.css?v=<hash> (cache busting)."""
    if path not in _h:
        with open(os.path.join(ROOT, path.lstrip("/")), "rb") as f:
            _h[path] = hashlib.sha1(f.read()).hexdigest()[:8]
    return f"{path}?v={_h[path]}"


def esc(s):
    return html.escape(str(s if s is not None else ""), quote=True)


def prefix(lang):
    return "" if lang == "en" else "/fa"


def home_url(lang):
    return f"{SITE}/" if lang == "en" else f"{SITE}/fa/"


def sl(slug):
    return slug.lower()


def proj_url(lang, slug):
    return f"{SITE}{prefix(lang)}/projects/{sl(slug)}/"


def last_change():
    try:
        out = subprocess.check_output(
            ["git", "log", "-1", "--format=%cs", "--", "src", "content", "tools/build.py"],
            cwd=ROOT, stderr=subprocess.DEVNULL, text=True).strip()
        if out:
            return out
    except Exception:  # noqa: BLE001
        pass
    return dt.date.today().isoformat()


LASTMOD = last_change()
SYNC_DAY = (SNAP.get("syncedAt") or "")[:10]
HOME_LASTMOD = max(LASTMOD, SYNC_DAY) if SYNC_DAY else LASTMOD

LANG_COLORS = {"Python": "#3572A5", "C++": "#f34b7d", "C": "#8a8a8a", "C#": "#178600", "VHDL": "#adb2cb",
               "Verilog": "#b2b7f8", "HTML": "#e34c26", "CSS": "#663399", "JavaScript": "#f1e05a",
               "TypeScript": "#3178c6", "MATLAB": "#e16737", "Java": "#b07219", "Shell": "#89e051",
               "Arduino": "#bd79d8", "Assembly": "#6E4C13", "QML": "#44a51c", "PHP": "#4F5D95"}


def rel_time(iso, lang):
    """Static HTML shows an absolute date (stable between builds); JS swaps in 'x days ago'."""
    return (iso or "")[:10]


# ───────────────────────── runtime JS ─────────────────────────
RUNTIME = r"""
function t(key) {
  const lang = document.documentElement.lang === "fa" ? "fa" : "en";
  return (I18N[lang] && I18N[lang][key]) || (I18N.en && I18N.en[key]) || key;
}
function fmt(key, vars) {
  let s = t(key);
  Object.keys(vars || {}).forEach(k => { s = s.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]); });
  return s;
}
/* Each language has its own URL (/ and /fa/), so switching = navigating. */
function setLang(lang) {
  const cur = document.documentElement.lang === "fa" ? "fa" : "en";
  if (lang !== "fa" && lang !== "en") lang = "en";
  if (lang === cur) return;
  location.href = (lang === "fa" ? "/fa/" : "/") + location.hash;
}
"""


def write_runtime():
    for lang in ("en", "fa"):
        d = {k: v for k, v in STR[lang].items()}
        data = {"en": {}, "fa": {}}
        data[lang] = d
        wr(f"js/i18n.{lang}.js",
           "/* generated by tools/build.py — edit content/*.json instead */\n"
           f"const I18N = {json.dumps(data, ensure_ascii=False)};\n{RUNTIME}")
    wr("js/site-config.js",
       "/* generated by tools/build.py from content/site.json */\n"
       f"window.SITE = {json.dumps(CFG)};\n")


# ───────────────────────── head ─────────────────────────
BOOT = ('<script>(function(){document.documentElement.classList.add("js");'
        'try{var t=localStorage.getItem("site_theme");if(t)document.documentElement.setAttribute("data-theme",t);}'
        'catch(e){}})();</script>')


def head(lang, title, desc, canonical, alternates, jsonld, og_type="website", robots="index, follow",
         og_alt=None, preload=True):
    s = STR[lang]
    other = "fa" if lang == "en" else "en"
    p = []
    p.append('<meta charset="UTF-8" />')
    p.append('<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />')
    p.append(f"<title>{esc(title)}</title>")
    p.append(f'<meta name="description" content="{esc(desc)}" />')
    p.append(f'<meta name="robots" content="{robots}, max-image-preview:large" />')
    p.append(f'<meta name="author" content="{NAME_EN}" />')
    p.append(f'<link rel="canonical" href="{canonical}" />')
    for hl, url in alternates:
        p.append(f'<link rel="alternate" hreflang="{hl}" href="{url}" />')
    p.append(f'<meta property="og:site_name" content="{NAME_EN}" />')
    p.append(f'<meta property="og:type" content="{og_type}" />')
    p.append(f'<meta property="og:title" content="{esc(title)}" />')
    p.append(f'<meta property="og:description" content="{esc(s["og_desc"] if og_type == "website" and canonical.endswith("/") and "/projects/" not in canonical else desc)}" />')
    p.append(f'<meta property="og:url" content="{canonical}" />')
    p.append(f'<meta property="og:locale" content="{LOCALES[lang]}" />')
    p.append(f'<meta property="og:locale:alternate" content="{LOCALES[other]}" />')
    p.append(f'<meta property="og:image" content="{OG_IMAGE}" />')
    p.append('<meta property="og:image:width" content="1200" />')
    p.append('<meta property="og:image:height" content="630" />')
    p.append(f'<meta property="og:image:alt" content="{esc(og_alt or title)}" />')
    p.append('<meta name="twitter:card" content="summary_large_image" />')
    p.append(f'<meta name="twitter:title" content="{esc(title)}" />')
    p.append(f'<meta name="twitter:description" content="{esc(desc)}" />')
    p.append(f'<meta name="twitter:image" content="{OG_IMAGE}" />')
    p.append('<meta name="color-scheme" content="dark light" />')
    p.append('<meta name="theme-color" content="#141824" />')
    p.append('<link rel="icon" href="/favicon.svg" type="image/svg+xml" />')
    p.append('<link rel="icon" href="/favicon.ico" sizes="48x48" />')
    p.append('<link rel="apple-touch-icon" href="/icons/icon-180.png" />')
    p.append('<link rel="manifest" href="/manifest.webmanifest" />')
    p.append(BOOT)
    if preload:
        fonts = (["inter-latin-wght-normal", "space-grotesk-latin-wght-normal"] if lang == "en"
                 else ["vazirmatn-arabic-400-normal", "vazirmatn-arabic-700-normal"])
        for f in fonts:
            p.append(f'<link rel="preload" href="/fonts/{f}.woff2" as="font" type="font/woff2" crossorigin />')
    for css in ("/css/fonts.css", "/css/tokens.css", "/css/site.css"):
        p.append(f'<link rel="stylesheet" href="{asset(css)}" />')
    p.append(f'<script type="application/ld+json">{json.dumps(jsonld, ensure_ascii=False)}</script>')
    return "\n".join(p)


