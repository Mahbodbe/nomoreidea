def build_home(lang):
    s = STR[lang]
    other = "fa" if lang == "en" else "en"
    tpl = rd("src", "template.html")
    stats = SNAP.get("stats", {})
    stars = sum(r.get("stars", 0) for r in SNAP.get("repos", []) if r["name"] not in CFG["hidden"])
    sync = ""
    if SYNC_DAY:
        sync = s["sync_note_fmt"].replace("{d}", SYNC_DAY)
    rep = {
        "{{LANG}}": lang, "{{DIR}}": s["dir"], "{{BODYCLASS}}": "fa-mode" if lang == "fa" else "",
        "{{ALT_HREF}}": "/fa/" if lang == "en" else "/", "{{ALT_LANG}}": other,
        "{{SWITCH_ARIA}}": esc(s["switch_language"]),
        "{{EN_ACTIVE}}": " is-active" if lang == "en" else "", "{{FA_ACTIVE}}": " is-active" if lang == "fa" else "",
        "{{ALT_HERO}}": esc(s["alt_hero"]), "{{ALT_W1}}": esc(s["alt_w1"]), "{{ALT_W2}}": esc(s["alt_w2"]),
        "{{OPEN_W1}}": esc(s["open_w1"]), "{{OPEN_W2}}": esc(s["open_w2"]),
        "{{STAT_REPOS}}": str(stats.get("repos", "—")), "{{STAT_STARS}}": str(stars),
        "{{STAT_FOLLOWERS}}": str(stats.get("followers", "—")), "{{STAT_SINCE}}": str(stats.get("since", "—")),
        "{{SYNCNOTE}}": esc(sync or s["sync_pending"]),
        "{{FEATURED}}": featured_html(lang), "{{GRID}}": grid_html(lang),
    }
    for k, v in rep.items():
        tpl = tpl.replace(k, v)
    tpl = fill_i18n(tpl, lang)

    canonical = home_url(lang)
    alternates = [("en", home_url("en")), ("fa", home_url("fa")), ("x-default", home_url("en"))]
    graph = {"@context": "https://schema.org", "@graph": [
        {"@type": "WebSite", "@id": f"{SITE}/#website", "url": f"{SITE}/", "name": NAME_EN,
         "alternateName": NAME_FA, "inLanguage": ["en", "fa"], "publisher": {"@id": f"{SITE}/#person"}},
        {"@type": "ProfilePage", "@id": canonical + "#profile", "url": canonical, "name": s["meta_title"],
         "description": s["meta_desc"], "inLanguage": lang, "isPartOf": {"@id": f"{SITE}/#website"},
         "mainEntity": {"@id": f"{SITE}/#person"}, "dateModified": HOME_LASTMOD,
         "primaryImageOfPage": {"@type": "ImageObject", "url": OG_IMAGE}},
        person(lang)]}
    hd = head(lang, s["meta_title"], s["meta_desc"], canonical, alternates, graph, og_alt=s["alt_hero"])
    tpl = tpl.replace("{{HEAD}}", hd)
    tpl = tpl.replace("{{LANG}}", lang)  # script src
    assert "{{" not in tpl, re.findall(r"\{\{[A-Z_0-9]+\}\}", tpl)
    wr("index.html" if lang == "en" else "fa/index.html", tpl)


